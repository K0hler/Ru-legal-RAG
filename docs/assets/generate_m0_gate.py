"""Regenerate the M0 decision from pinned evidence; never inspect gold labels."""

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2]


def acceptance_criteria(plan: str) -> dict[str, list[str]]:
    criteria = {}
    for section in re.split(r"(?m)^### ", plan)[1:]:
        match = re.match(r"(M0-\d+(?:A)?) —", section)
        if match:
            acceptance = section.split("Acceptance:\n\n", 1)[1].split("\n\n", 1)[0]
            criteria[match[1]] = [
                re.sub(r"\s+", " ", item).strip()
                for item in acceptance.removeprefix("- ").split("\n- ")
            ]
    if "M0 passes only when:\n\n" in plan:
        acceptance = plan.split("M0 passes only when:\n\n", 1)[1].split("\n\n", 1)[0]
        criteria["M0-GATE"] = acceptance.removeprefix("- ").split("\n- ")
    return criteria


def gate_decision(expected: set[str], decisions: dict[str, dict]) -> str:
    if set(decisions) != expected:
        raise ValueError("assessment must cover every acceptance criterion exactly")
    states = {record["status"] for record in decisions.values()}
    if not states <= {"pass", "fail", "unresolved"}:
        raise ValueError("unsupported acceptance status")
    return "fail" if "fail" in states else "unresolved" if "unresolved" in states else "pass"


def verify_hashes(root: Path, files: dict[str, str], *, normalize_lf: bool = False) -> list[str]:
    problems = []
    for name, expected in sorted(files.items()):
        path = root / name
        if not path.is_file():
            problems.append(f"Missing evidence: {name}")
        else:
            payload = path.read_bytes()
            if normalize_lf:
                payload = payload.replace(b"\r\n", b"\n")
            if hashlib.sha256(payload).hexdigest() != expected:
                problems.append(f"Changed evidence: {name}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, default=ROOT / "docs/M0_GATE_REPORT.md")
    parser.add_argument("--summary", type=Path, default=ROOT / "data/m0-12-gate/gate.json")
    args = parser.parse_args(argv)
    assessment = json.loads((ROOT / "docs/M0_GATE_ASSESSMENT.json").read_text("utf-8"))
    freeze = json.loads((ROOT / "docs/M0_CONTRACT_FREEZE.json").read_text("utf-8"))
    plan = acceptance_criteria((ROOT / "docs/M0_IMPLEMENTATION_PLAN.md").read_text("utf-8"))
    criteria = {
        f"{slice_id}.{index}": text
        for slice_id, entries in plan.items()
        for index, text in enumerate(entries, 1)
    }
    decisions = assessment["criteria"]
    status = gate_decision(set(criteria), decisions)
    problems = verify_hashes(ROOT, freeze["file_sha256s"], normalize_lf=True)
    for local in (True, False):
        files = {name: digest for name, digest in assessment["evidence_sha256s"].items()
                 if name.startswith("data/") == local}
        problems.extend(verify_hashes(ROOT, files, normalize_lf=not local))
    criteria_hash = hashlib.sha256(json.dumps(criteria, sort_keys=True).encode()).hexdigest()
    if criteria_hash != assessment["acceptance_sha256"]:
        problems.append("Acceptance criteria changed; reassessment required")
    if problems:
        status = "unresolved"
    evidence = assessment["evidence"]
    pilot = json.loads((ROOT / evidence["pilot"]).read_text("utf-8")) if not problems else None
    counts = Counter(record["status"] for record in decisions.values())
    blockers = [key for key, record in decisions.items() if record["status"] != "pass"]
    summary = {
        "schema_version": "m0-gate/1",
        "recorded_on": assessment["recorded_on"],
        "status": status,
        "m1_allowed": status == "pass",
        "criterion_counts": dict(sorted(counts.items())),
        "blocking_criteria": blockers,
        "evidence_problems": problems,
        "contract_version": freeze["contract_version"],
    }
    lines = [
        "# M0 gate report",
        "",
        f"**Recorded:** {assessment['recorded_on']}. **Gate:** `{status}`. "
        f"**M1 allowed:** `{str(summary['m1_allowed']).lower()}`.",
        "",
        "Generated by `python docs/assets/generate_m0_gate.py` from retained historical "
        "runs, recorded human decisions and engineering assessments. Hash verification "
        "confirms evidence integrity; it does not replace legal review or a fresh live-source check.",
        "",
        "M0-12 reporting and contract freeze are implemented. "
        f"Blocking criteria: {', '.join(blockers) or 'none'}. "
        "A failed or unresolved gate blocks M1 until the evidence is completed and reassessed.",
        "",
        "## Recorded acquisition and review",
        "",
    ]
    if pilot is not None:
        lines += ["| Pass | new | unchanged | changed | failed | Raw assets added |",
                  "|---|---:|---:|---:|---:|---:|"]
        for run in pilot["passes"]:
            c = run["counts"]
            lines.append(f"| {run['pass']} | {c['new']} | {c['unchanged']} | "
                         f"{c['changed']} | {c['failed']} | {run['raw_assets_added']} |")
        lines += ["", f"Pilot `{pilot['pilot_id']}`: `{json.dumps(pilot['metrics'], sort_keys=True)}`.",
                  "", f"Standalone acquisition exceptions: {len(pilot['exceptions'])}; "
                  f"duplicate source items: {len(pilot['duplicate_source_items'])}. "
                  "These zero counts do not mean complete legal coverage.", "",
                  "| Act | Consolidated text | Amendment coverage | Temporal evidence |",
                  "|---|---|---|---|"]
        for act in pilot["coverage"]:
            amendment = act["amendments"]
            lines.append(f"| {act['label']} | {act['consolidated_edition']} | "
                         f"{amendment['status']} ({amendment['acquired']} acquired) | "
                         f"{act['temporal_evidence']} |")
    lines += [""]
    for finding in assessment["recorded_findings"]:
        lines += [finding, ""]
    lines += ["## Evidence register", "",
              "Paths below are relative to the repository root; complete live/private records stay ignored.", ""]
    lines += [f"- `{name}`: `{path}`" for name, path in evidence.items()]
    lines += ["", "The assessment pins evidence hashes in [M0_GATE_ASSESSMENT.json](M0_GATE_ASSESSMENT.json). "
              "[M0_CONTRACT_FREEZE.json](M0_CONTRACT_FREEZE.json) pins implementation and fixture hashes. "
              "[M0_CONTRACTS.md](M0_CONTRACTS.md) defines the frozen acquisition and M1 handoff boundary.",
              "", "## Acceptance decisions", "",
              f"{len(criteria)} criteria: {counts['pass']} pass, {counts['fail']} fail, "
              f"{counts['unresolved']} unresolved. Recorded assessments are explicit; "
              "no failed or unresolved criterion becomes a future TODO.", ""]
    for slice_id, entries in plan.items():
        lines += [f"### {slice_id}", "", "| Criterion | Status | Evidence and rationale |", "|---|---|---|"]
        for index, text in enumerate(entries, 1):
            key = f"{slice_id}.{index}"
            record = decisions[key]
            refs = ", ".join(f"`{ref}`" for ref in record["evidence"])
            lines.append(f"| {key}: {text.replace('|', '/')} | {record['status']} | "
                         f"{refs}. {record['rationale']} |")
        lines.append("")
    if problems:
        lines += ["## Evidence verification failures", "", *[f"- {p}" for p in problems], ""]
    lines += ["## Transition rule", "", "Exit code `0` permits M1 only when every criterion passes "
              "and all pinned evidence is present and unchanged. Exit code `2` blocks M1. "
              "Rewriting an assessment is not reviewer approval. Legal admission blockers "
              "and bulk-access restrictions remain separate from the milestone decision.", ""]
    for path, payload in [(args.report, "\n".join(lines)),
                          (args.summary, json.dumps(summary, indent=2, sort_keys=True) + "\n")]:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(payload, encoding="utf-8", newline="\n")
    print(json.dumps(summary, sort_keys=True))
    return 0 if summary["m1_allowed"] else 2


if __name__ == "__main__":
    raise SystemExit(main())
